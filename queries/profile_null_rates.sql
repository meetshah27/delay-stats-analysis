-- Data profile: share of null values per column, all months.
select
    1 - cast(count(dayofmonth) as double) / count(*) as dayofmonth,
    1 - cast(count(dayofweek) as double) / count(*) as dayofweek,
    1 - cast(count(flightdate) as double) / count(*) as flightdate,
    1 - cast(count(reporting_airline) as double) / count(*) as reporting_airline,
    1 - cast(count(tail_number) as double) / count(*) as tail_number,
    1 - cast(count(flight_number_reporting_airline) as double) / count(*) as flight_number_reporting_airline,
    1 - cast(count(origin) as double) / count(*) as origin,
    1 - cast(count(originstate) as double) / count(*) as originstate,
    1 - cast(count(dest) as double) / count(*) as dest,
    1 - cast(count(deststate) as double) / count(*) as deststate,
    1 - cast(count(crsdeptime) as double) / count(*) as crsdeptime,
    1 - cast(count(depdelay) as double) / count(*) as depdelay,
    1 - cast(count(crsarrtime) as double) / count(*) as crsarrtime,
    1 - cast(count(arrdelay) as double) / count(*) as arrdelay,
    1 - cast(count(arrdelayminutes) as double) / count(*) as arrdelayminutes,
    1 - cast(count(arrdel15) as double) / count(*) as arrdel15,
    1 - cast(count(cancelled) as double) / count(*) as cancelled,
    1 - cast(count(cancellationcode) as double) / count(*) as cancellationcode,
    1 - cast(count(diverted) as double) / count(*) as diverted,
    1 - cast(count(distance) as double) / count(*) as distance,
    1 - cast(count(carrierdelay) as double) / count(*) as carrierdelay,
    1 - cast(count(weatherdelay) as double) / count(*) as weatherdelay,
    1 - cast(count(nasdelay) as double) / count(*) as nasdelay,
    1 - cast(count(securitydelay) as double) / count(*) as securitydelay,
    1 - cast(count(lateaircraftdelay) as double) / count(*) as lateaircraftdelay,
    1 - cast(count(primary_delay_cause) as double) / count(*) as primary_delay_cause
from ontime
